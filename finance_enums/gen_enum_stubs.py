#!/usr/bin/env python3
"""Generate _enum_types.pyi, the type stub for the native IntEnum families.

The families are built in Rust and installed into ``finance_enums`` at import
time, so type checkers cannot see them. The stub declares each family with its
members, including the acronym aliases exposed as members, read from the
runtime classes.
"""

import keyword
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
stub_path = root / "finance_enums" / "_enum_types.pyi"

# Methods the domain submodules attach to native families at import time.
ATTACHED_METHODS = {
    "CountryCode": ["def country_name(self) -> str: ...", "def code3(self) -> CountryCode3: ..."],
    "CountryCode3": ["def country_name(self) -> str: ..."],
    "Currency": [
        "def currency_name(self) -> str: ...",
        "def is_iso4217(self) -> bool: ...",
        "def record(self) -> CurrencyRecord: ...",
    ],
    "ExchangeCode": [
        "def record(self) -> ExchangeRecord: ...",
        "def market_name(self) -> str: ...",
        "def market_category(self) -> MICMarketCategory | None: ...",
        "def regulatory_flags(self) -> tuple[VenueRegulatoryFlag, ...]: ...",
        "def has_regulatory_flag(self, regulatory_flag: VenueRegulatoryFlag | str) -> bool: ...",
    ],
}


def generate_stub() -> str:
    sys.path.insert(0, str(root))
    import finance_enums

    lines = [
        "# Generated by finance_enums/gen_enum_stubs.py from the native extension. Do not edit.",
        "from enum import IntEnum",
        "",
        "from .currency import CurrencyRecord",
        "from .exchange import ExchangeRecord",
    ]
    for family in finance_enums.__all_families__:
        cls = getattr(finance_enums, family)
        lines += ["", f"class {family}(IntEnum):"]
        for name, member in cls._member_map_.items():
            if name.isidentifier() and not keyword.iskeyword(name):
                lines.append(f"    {name} = {member.value}")
        methods = ATTACHED_METHODS.get(family, [])
        if methods:
            lines.append("")
            lines += [f"    {method}" for method in methods]
    return "\n".join(lines) + "\n"


def main():
    stub_path.write_text(generate_stub(), encoding="utf-8")
    print(f"Generated {stub_path.name}")


if __name__ == "__main__":
    main()
